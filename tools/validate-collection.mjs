import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {validateReading} from '../reading/quality.mjs';
const root=process.env.SITE_ROOT||'.',read=p=>fs.readFileSync(`${root}/${p}`,'utf8');
const b=JSON.parse(read('reading/bank.json')),exam=JSON.parse(read('exam/bank.json'));
assert.equal(b.version,2);assert.equal(b.items.length,222);assert.deepEqual(validateReading(b.items),[]);
assert.deepEqual(exam.items.filter(x=>x.id.startsWith('r2-')),b.items);
const context={};vm.runInNewContext(read('reading/library-bank.js'),context);
assert.deepEqual(JSON.parse(JSON.stringify(context.__TOEFL_READING_V2__)),b.items);
const listening=exam.items.filter(x=>!x.id.startsWith('r2-'));
const audit=JSON.parse(read('docs/READING_QUALITY_AUDIT.json'));
assert.equal(listening.length,800);assert.equal(createHash('sha256').update(JSON.stringify(listening)).digest('hex'),audit.listening.sha256);
const bundle=read('assets/index-0Qc6vs45.js');assert(bundle.includes('__TOEFL_READING_REPLACEMENTS__'));assert(bundle.includes('selectLibrary(pool,count)'));assert(read('library.html').includes('reading/library-bank.js'));
console.log('PASS: 222 Reading activities / 1,400 items; library and exam agree; 800 Listening activities match baseline fingerprint.');
