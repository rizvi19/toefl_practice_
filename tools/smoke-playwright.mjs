import assert from "node:assert/strict";
import fs from "node:fs";
import vm from "node:vm";
import {chromium} from "playwright";
const root=process.env.SITE_ROOT||".";
const auxiliary=fs.readFileSync(root+"/collections/academic-topics-additional.js","utf8");
const source=fs.readFileSync(root+"/collections/complete-words-200.js","utf8");
const sandbox={window:{}};vm.runInNewContext(auxiliary,sandbox);vm.runInNewContext(source,sandbox);
const activity=sandbox.window.__TOEFL_CTW_200_EXT__[0];
const browser=await chromium.launch({headless:true});
const page=await browser.newPage();
const errors=[],bad=[];
page.on("pageerror",e=>errors.push(e.message));
page.on("response",r=>{if(r.status()>=400)bad.push(r.url()+" "+r.status())});
const url="http://127.0.0.1:4177/toefl_practice_/";
await page.goto(url,{waitUntil:"networkidle"});
await page.getByRole("button",{name:/Practice library/i}).first().click();
await page.getByRole("heading",{name:"Complete the Words — Official-format 200"}).waitFor();
await page.getByRole("button",{name:"Browse all 200 passages"}).click();
const rows=page.locator(".activity-row");
assert.equal(await rows.count(),200,"200 public library rows");
assert.equal((await rows.nth(3).innerText()).includes("CTW 2026 · 001"),true);
await rows.nth(3).getByRole("button",{name:/Practice/}).click();
assert.equal(await page.locator(".word-group").count(),10,"10 complete blanks");
const expected=activity.pieces.filter(x=>typeof x==="object");
const allSlots=expected.reduce((n,x)=>n+x.answer.length,0);
assert.equal(await page.locator(".letter-slot").count(),allSlots,"fixed letter slot count");
await page.locator(".letter-slot").first().fill(expected[0].answer[0]);
assert.equal(await page.locator(".letter-slot").first().inputValue(),expected[0].answer[0]);
await page.waitForFunction(({id,letter})=>{
 try{return JSON.parse(localStorage.getItem("toefl-studio-v1")).session?.responses?.[id]?.blanks?.[0]?.[0]===letter}catch{return false}
},{id:activity.id,letter:expected[0].answer[0]});
await page.reload({waitUntil:"networkidle"});
await page.getByRole("button",{name:/Resume session/i}).click();
assert.equal(await page.locator(".letter-slot").first().inputValue(),expected[0].answer[0],"browser persistence on reload");
for(let w=0;w<10;w++){
 const inputs=page.locator(".word-group").nth(w).locator("input");
 const answer=expected[w].answer;
 for(let k=0;k<answer.length;k++) await inputs.nth(k).fill(answer[k]);
}
await page.getByRole("button",{name:/Check answers/i}).click();
await page.getByText("10 / 10 correct").waitFor();
await page.getByRole("button",{name:/Finish & see report/i}).click();
assert.equal((await page.locator("body").innerText()).includes("10 / 10"),true);
const audio=await page.request.get(url+"audio/repeat-1.wav");
assert.equal(audio.status(),200,"existing audio available at subpath");
const doc=await page.request.get(url+"docs/format-and-sources.html");
assert.equal(doc.status(),200,"original docs available at subpath");
await page.getByRole("button",{name:/Practice library/i}).first().click();
await page.getByRole("button",{name:/Full practice form/i}).click();
assert.equal((await page.locator(".practice-toolbar").innerText()).includes("60"),true,"original full form retains 60 activity screens / 120 questions");
assert.equal(errors.length,0,"No JS errors: "+errors.join("; "));
assert.equal(bad.length,0,"No failed resources: "+bad.join("; "));
console.log(JSON.stringify({browser:"PASS",allCompleteWordsRows:200,slots:allSlots,grading:"10/10",persistence:"PASS",originalFullFormScreens:60,gitHubPagesSubpath:"PASS",audio:"PASS",docs:"PASS"}));
await browser.close();
