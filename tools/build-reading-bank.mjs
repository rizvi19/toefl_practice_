import fs from 'node:fs';
import short from '../reading/short.mjs';
import long from '../reading/long.mjs';
import chains from '../reading/chains.mjs';
import academic from '../reading/academic.mjs';
import cloze from '../reading/cloze.mjs';
import {validateReading,wordCount,complexity} from '../reading/quality.mjs';
const retained=JSON.parse(fs.readFileSync('reading/retained-cloze.json','utf8'));
const paragraphs=[...retained,...cloze.map(([title,text],i)=>({title,text,level:i%2?'advanced':'intermediate'}))];
function pieces(text){
  const first=text.indexOf('. ')+2;
  if(first<2)throw Error('Missing intact opening sentence');
  // Complete opening sentence, then every second word; include both function and content words.
  const words=[...text.slice(first).matchAll(/\b[A-Za-z]+(?:['’][A-Za-z]+)?\b/g)];
  // One-letter words and contractions cannot support a useful alphabetic suffix deletion.
  const selected=words.filter((x,i)=>i%2===1&&x[0].length>1&&/^[a-z]+$/i.test(x[0])).slice(0,10);
  if(selected.length!==10||selected.some(x=>!/^[a-z]+$/i.test(x[0])))throw Error('Cloze deletion requires ten alphabetic words');
  const result=[];let prior=0;
  for(const x of selected){const pos=first+x.index,split=Math.ceil(x[0].length/2),pre=x[0].slice(0,split),answer=x[0].slice(split);
    if(!answer)throw Error('Cannot delete the second half of a one-letter word');
    const end=text.indexOf('.',pos),begin=text.lastIndexOf('. ',pos-1)+2;
    const evidence=text.slice(begin<2?0:begin,end<0?text.length:end+1).trim();
    result.push(text.slice(prior,pos),{pre,answer,evidence,explanation:`“${x[0]}” completes the sentence: “${evidence}” The visible prefix and context identify the word; enter its remaining ${answer.length} letter${answer.length===1?'':'s'}.`});prior=pos+x[0].length;
  }
  result.push(text.slice(prior));return result;
}
const words=paragraphs.map((x,i)=>({id:`r2-c${String(i+1).padStart(3,'0')}`,type:'complete-words',variant:'complete-words',title:x.title,topic:x.title,family:`r2-c${i+1}`,level:x.level,difficulty:x.level==='advanced'?'Hard':'Medium',pack:'Reading 2026 · Complete the Words',words:wordCount(x.text),pieces:pieces(x.text),seconds:180}));
// Higher-complexity half of each task pool is Advanced; stable ordering preserves IDs.
function levels(group){const scored=group.map(x=>({...x,complexity:complexity(x)})),ranked=[...scored].sort((a,b)=>a.complexity.score-b.complexity.score||a.id.localeCompare(b.id)),advancedIds=new Set(ranked.slice(Math.ceil(ranked.length/2)).map(x=>x.id));return scored.map(x=>({...x,level:advancedIds.has(x.id)?'advanced':'intermediate',difficulty:advancedIds.has(x.id)?'Hard':'Medium'}));}
const leveledWords=levels(words),everyday=[...levels(short),...levels(long),...levels(chains)],academics=levels(academic);
const items=[...leveledWords,...everyday,...academics];
const errors=validateReading(items);if(errors.length)throw Error(errors.join('\n'));
const bank={version:2,bankVersion:'reading-2026-v2',provenance:'Original independent practice; references inform task structure only. Fifty distinct original site cloze paragraphs retained; overlapping variants retired. Editorial levels are not calibrated.',items};
fs.writeFileSync('reading/bank.json',JSON.stringify(bank,null,2)+'\n');
// The existing compiled library has ten Reading slots in its 60-activity full form.
// Replace only those slots; all Writing/Speaking/Listening objects stay intact.
const replacements=Object.fromEntries([
 ...['words-01','words-02','words-03'].map((id,i)=>[id,leveledWords[i]]),
 ...['daily-01','daily-02','daily-03','daily-04','daily-05'].map((id,i)=>[id,everyday[i]]),
 ...['academic-01','academic-02'].map((id,i)=>[id,academics[i]])]);
fs.writeFileSync('reading/library-bank.js',`// Generated by tools/build-reading-bank.mjs. Do not edit.\nObject.assign(globalThis,${JSON.stringify({__TOEFL_READING_V2__:items,__TOEFL_READING_REPLACEMENTS__:replacements,__READING_CTW__:leveledWords.slice(3),__READING_DAILY__:everyday.slice(5),__READING_ACADEMIC__:academics.slice(2)})});\n`);
console.log(`Reading bank: ${items.length} distinct activities; ${items.reduce((n,x)=>n+(x.pieces?10:x.questions.length),0)} scored practice items.`);
